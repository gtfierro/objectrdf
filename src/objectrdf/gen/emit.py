"""Emitter: schema IR -> Python source for a generated ontology package.

The output is deliberately boring, declarative code: module-level
PropertySpecs, one class per ontology class with its ``_classinfo``, typed
descriptors with PEP 258-style attribute docstrings (editors surface these on
hover), and an explicit ``__init__`` wherever a class introduces properties —
that signature is what gives call-site completion and required-argument
checking in the IDE.

Ontology documentation flows into every docstring: class docstrings carry the
``skos:definition`` plus provenance (ontology, IRI); attribute docstrings
carry the property's definition and predicate.
"""

from __future__ import annotations

from .overlays import Overlay
from .schema import CPConstraintIR, ClassIR, PropIR, SchemaIR

_HEADER = '''\
"""{name} ontology classes, generated by `objectrdf gen`. DO NOT EDIT.

Source ontology: {iri}{version_line}
Regenerate with:  objectrdf gen --name {name} --out <this directory> ...
"""

# ruff: noqa
from __future__ import annotations

# Runtime imports are aliased with a leading underscore so ontology classes
# are free to use any name (e.g. RealEstateCore defines a class `Entity`).
from typing import Iterable as _Iterable

from objectrdf.core import (
    ClassInfo as _ClassInfo,
    CPConstraint as _CPConstraint,
    CPSlot as _CPSlot,
    Entity as _EntityBase,
    EnumOne as _EnumOne,
    EnumSet as _EnumSet,
    EnumValue as _EnumValue,
    Lit as _Lit,
    Model as _Model,
    OntologyInfo as _OntologyInfo,
    PropertySpec as _PropertySpec,
    Registry as _Registry,
    Rel as _Rel,
    RelOne as _RelOne,
    ValueOne as _ValueOne,
    provided as _provided,
)

ONTOLOGY = _OntologyInfo(
    name={name_r},
    iri={iri_r},
    version={version_r},
    source={source_r},
)

_REGISTRY = _Registry(ONTOLOGY)
'''


def emit_module(ir: SchemaIR, overlay: Overlay | None = None) -> str:
    """Render the complete generated (package) module."""
    parts = [
        _HEADER.format(
            name=ir.ontology_name,
            iri=ir.ontology_iri,
            version_line=f"\nOntology version: {ir.version}" if ir.version else "",
            name_r=repr(ir.ontology_name),
            iri_r=repr(ir.ontology_iri),
            version_r=repr(ir.version),
            source_r=repr(ir.source),
        )
    ]
    if ir.enums:
        parts.append(
            "from . import enums as enums\n\n_REGISTRY.register_enums(enums)\n"
        )
    by_name = {c.name: c for c in ir.classes}
    emitted: set[str] = set()
    for cls in ir.classes:
        parts.append(_emit_class(cls, by_name, emitted, ir))
        emitted.add(cls.name)
    if overlay is not None:
        parts.append(_emit_overlay(overlay, ir))
    names = ", ".join(repr(c.name) for c in ir.classes)
    parts.append(f'\n__all__ = ["ONTOLOGY", {names}]\n')
    return "\n".join(parts)


def _emit_class(
    cls: ClassIR,
    by_name: dict[str, ClassIR],
    emitted: set[str],
    ir: SchemaIR,
) -> str:
    # Only inherit from parents already emitted; a dropped link (cycle) still
    # leaves the class rooted at the runtime Entity base.
    bases = [p for p in cls.parents if p in emitted] or ["_EntityBase"]

    lines: list[str] = []
    for prop in cls.own_props:
        lines.append(_emit_spec(cls, prop))

    lines.append(f"class {cls.name}({', '.join(bases)}):")
    lines.append(_docstring(_class_doc(cls, ir), indent="    "))
    lines.append("")
    lines.append("    _classinfo = _ClassInfo(")
    lines.append(f"        iri={cls.iri!r},")
    lines.append("        ontology=ONTOLOGY,")
    lines.append("        registry=_REGISTRY,")
    lines.append(f"        label={cls.label!r},")
    lines.append(f"        definition={cls.definition!r},")
    if cls.abstract:
        lines.append("        abstract=True,")
    if cls.own_props:
        specs = ", ".join(_spec_var(cls, p) for p in cls.own_props)
        lines.append(f"        properties=({specs},),")
    if cls.cp_slots:
        lines.append("        cp_slots=(")
        for slot in cls.cp_slots:
            lines.append(
                f"            _CPSlot(cp_class={slot.cp_class!r}, "
                f"direction={slot.direction!r}, medium={slot.medium!r}, "
                f"medium_options={slot.medium_options!r}, "
                f"min_count={slot.min_count}, max_count={slot.max_count!r}),"
            )
        lines.append("        ),")
    if cls.cp_constraints:
        lines.append("        cp_constraints=(")
        for constraint in cls.cp_constraints:
            lines.extend(_emit_cp_constraint(constraint, indent="            "))
        lines.append("        ),")
    lines.append("    )")

    for prop in cls.own_props:
        lines.append("")
        lines.append(f"    {_emit_descriptor(cls, prop)}")
        doc = prop.definition or prop.label or prop.name
        lines.append(_docstring(f"{doc} ({prop.predicate})", indent="    "))

    init = _emit_init(cls, by_name)
    if init:
        lines.append("")
        lines.append(init)

    return "\n".join(lines) + "\n"


def _emit_cp_constraint(
    constraint: CPConstraintIR, *, indent: str
) -> list[str]:
    """Render one recursive connection constraint as generated metadata."""
    if constraint.operator == "slot":
        assert constraint.slot is not None
        slot = constraint.slot
        return [
            f"{indent}_CPConstraint(operator='slot', slot=_CPSlot("
            f"cp_class={slot.cp_class!r}, direction={slot.direction!r}, "
            f"medium={slot.medium!r}, medium_options={slot.medium_options!r}, "
            f"min_count={slot.min_count}, "
            f"max_count={slot.max_count!r})),"
        ]
    if constraint.operator == "opaque":
        return [f"{indent}_CPConstraint(operator='opaque'),"]
    lines = [
        f"{indent}_CPConstraint(operator={constraint.operator!r}, children=("
    ]
    for child in constraint.children:
        lines.extend(_emit_cp_constraint(child, indent=indent + "    "))
    lines.append(f"{indent})),")
    return lines


def _emit_spec(cls: ClassIR, prop: PropIR) -> str:
    args = [
        f"name={prop.name!r}",
        f"predicate={prop.predicate!r}",
        f"kind={prop.kind!r}",
    ]
    if prop.label is not None:
        args.append(f"label={prop.label!r}")
    if prop.definition is not None:
        args.append(f"definition={prop.definition!r}")
    if prop.kind == "object" and prop.ranges:
        args.append(f"ranges={prop.ranges!r}")
    if prop.kind == "literal":
        args.append(f"datatype={prop.datatype}")
    if prop.kind == "enum" and prop.enum_ranges:
        args.append(f"enum_ranges={prop.enum_ranges!r}")
    if prop.required:
        args.append("required=True")
    if prop.max_count is not None:
        args.append(f"max_count={prop.max_count}")
    if prop.inverse is not None:
        args.append(f"inverse={prop.inverse!r}")
    joined = ",\n    ".join(args)
    return f"{_spec_var(cls, prop)} = _PropertySpec(\n    {joined},\n)\n"


def _spec_var(cls: ClassIR, prop: PropIR) -> str:
    return f"_P_{cls.name}_{prop.name}"


def _emit_descriptor(cls: ClassIR, prop: PropIR) -> str:
    var = _spec_var(cls, prop)
    if prop.kind == "value":
        return f"{prop.name}: _ValueOne[object] = _ValueOne({var})"
    if prop.kind == "literal":
        return f"{prop.name}: _Lit[{prop.datatype}] = _Lit({var})"
    if prop.kind == "enum":
        if prop.max_count == 1:
            return f"{prop.name}: _EnumOne[_EnumValue] = _EnumOne({var})"
        return f"{prop.name}: _EnumSet[_EnumValue] = _EnumSet({var})"
    target = _range_union(prop)
    if prop.max_count == 1:
        return f"{prop.name}: _RelOne[{target}] = _RelOne({var})"
    return f"{prop.name}: _Rel[{target}] = _Rel({var})"


def _range_union(prop: PropIR) -> str:
    return " | ".join(prop.ranges) if prop.ranges else "_EntityBase"


def _effective_props(cls: ClassIR, by_name: dict[str, ClassIR]) -> dict[str, PropIR]:
    """name -> spec including inherited, subclass declarations winning."""
    merged: dict[str, PropIR] = {}
    for parent in cls.parents:
        if parent in by_name:
            merged.update(_effective_props(by_name[parent], by_name))
    for prop in cls.own_props:
        merged[prop.name] = prop
    return merged


def _emit_init(cls: ClassIR, by_name: dict[str, ClassIR]) -> str:
    """Typed constructor; emitted when this class changes the property set.

    Classes that inherit an identical signature simply inherit ``__init__``
    (keeps generated files compact for deep taxonomies like Brick's).
    """
    effective = _effective_props(cls, by_name)
    if not effective:
        return ""
    if not cls.own_props and cls.parents:
        # Multiple inheritance may combine disjoint property sets. Inherit a
        # constructor only when one direct parent already exposes the complete
        # effective signature.
        effective_names = set(effective)
        if any(
            set(_effective_props(by_name[parent], by_name)) == effective_names
            for parent in cls.parents
            if parent in by_name
        ):
            return ""

    props = sorted(effective.values(), key=lambda p: (not p.required, p.name))
    params: list[str] = []
    for prop in props:
        params.append(f"        {prop.name}: {_param_annotation(prop)},")
    passthrough = "\n".join(f"                {p.name}={p.name}," for p in props)
    param_block = "\n".join(params)
    return f"""\
    def __init__(
        self,
        name: str | None = None,
        *,
{param_block}
        label: str | None = None,
        comment: str | None = None,
        model: _Model | None = None,
    ) -> None:
        # Funnel straight to the runtime base: generated __init__ methods are
        # typed sugar, not a cooperative chain (parents' signatures differ).
        _EntityBase.__init__(
            self,
            name,
            label=label,
            comment=comment,
            model=model,
            **_provided(
{passthrough}
            ),
        )"""


def _param_annotation(prop: PropIR) -> str:
    if prop.kind == "value":
        annotation = "object | None"
        return annotation if prop.required else f"{annotation} = None"
    if prop.kind == "literal":
        annotation = f"{prop.datatype} | None"
        return annotation if prop.required else f"{annotation} = None"
    if prop.kind == "enum":
        if prop.max_count == 1:
            annotation = "_EnumValue | None"
            return annotation if prop.required else f"{annotation} = None"
        annotation = "_Iterable[_EnumValue]"
        return annotation if prop.required else f"{annotation} = ()"
    union = _range_union(prop)
    if prop.max_count == 1:
        annotation = f"{union} | None"
        return annotation if prop.required else f"{annotation} = None"
    annotation = f"_Iterable[{union}]"
    return annotation if prop.required else f"{annotation} = ()"


def _class_doc(cls: ClassIR, ir: SchemaIR) -> str:
    body = cls.definition or cls.label or cls.name
    provenance = f"Ontology: {ir.ontology_name} — {cls.iri}"
    return f"{body}\n\n{provenance}"


def _docstring(text: str, indent: str) -> str:
    """Render text as a docstring literal, safely escaped.

    Triple-quoted when the text is benign; falls back to a repr literal
    (still a valid docstring position) when it contains tricky characters.
    """
    if '"""' not in text and "\\" not in text and not text.endswith('"'):
        body = text.replace("\r", "")
        if "\n" in body:
            body = body.replace("\n", f"\n{indent}")
            return f'{indent}"""{body}\n{indent}"""'
        return f'{indent}"""{body}"""'
    return f"{indent}{text!r}"


_ENUMS_HEADER = '''\
"""{name} enumeration constants, generated by `objectrdf gen`. DO NOT EDIT.

Flat constants named after the ontology local names (``Fluid-Air`` ->
``Fluid_Air``); each value also exposes children as attributes for
hierarchical access. See objectrdf.core.enums.
"""

# ruff: noqa
from __future__ import annotations

from objectrdf.core import EnumValue as _EnumValue

'''


def emit_enums_module(ir: SchemaIR) -> str:
    """Render the ``enums`` submodule (empty string when no enums)."""
    if not ir.enums:
        return ""
    lines = [_ENUMS_HEADER.format(name=ir.ontology_name)]
    for member in ir.enums:
        args = [repr(member.iri)]
        if member.label is not None:
            args.append(f"label={member.label!r}")
        if member.definition is not None:
            args.append(f"definition={member.definition!r}")
        if member.parent is not None:
            args.append(f"parent={member.parent}")
        lines.append(f"{member.name} = _EnumValue({', '.join(args)})")
        doc = member.definition or member.label
        if doc:
            lines.append(_docstring(doc, indent=""))
    names = ",\n    ".join(repr(m.name) for m in ir.enums)
    lines.append(f"\n__all__ = [\n    {names},\n]")
    return "\n".join(lines) + "\n"


def _emit_overlay(overlay: Overlay, ir: SchemaIR) -> str:
    """UX registrations (>> sugar, containment table) from the overlay.

    Entries referencing classes/properties the ontology didn't yield are
    skipped with a comment, so an overlay can be written against the union
    of ontology versions.
    """
    names = ir.class_names()
    props = {
        c.name: set(_effective_props(c, {x.name: x for x in ir.classes}))
        for c in ir.classes
    }
    lines = ["", "# -- UX overlay: operator sugar and containment rules --", ""]
    if overlay.connector:
        if "Connectable" in names:
            lines.append(
                "from objectrdf.connect223 import S223Connector as _S223Connector"
            )
            lines.append("")
            lines.append(
                "Connectable._CONNECTOR = _S223Connector("
                f"_REGISTRY, connection_classes={overlay.connection_classes!r})"
            )
        else:
            lines.append("# skipped: connector (no Connectable in this ontology)")
    for class_name, prop in overlay.rshift.items():
        if class_name in names and prop in props.get(class_name, set()):
            lines.append(f"{class_name}._RSHIFT = {prop!r}")
        else:
            lines.append(
                f"# skipped: rshift {class_name}.{prop} (not in this ontology)"
            )
    for rule in overlay.containment:
        container, child, prop, edge_from = rule
        prop_owner = container if edge_from == "container" else child
        if (
            container in names
            and child in names
            and prop in props.get(prop_owner, set())
        ):
            lines.append(
                f"_REGISTRY.containment.register("
                f"{container!r}, {child!r}, {prop!r}, edge_from={edge_from!r})"
            )
        else:
            lines.append(
                f"# skipped: containment {container}/{child} via {prop} "
                f"(not in this ontology)"
            )
    return "\n".join(lines) + "\n"
