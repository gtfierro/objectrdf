"""Compile named RDF individuals into immutable Python reference constants."""

from __future__ import annotations

from dataclasses import dataclass

import rdflib
from rdflib import RDF, RDFS, SKOS, URIRef

from objectrdf.gen import naming


@dataclass(frozen=True)
class VocabularyTerm:
    """One named individual selected by RDF type."""

    name: str
    iri: str
    label: str | None
    definition: str | None
    types: tuple[str, ...]


def _text(
    graph: rdflib.Graph,
    subject: URIRef,
    predicate: URIRef,
) -> str | None:
    values = sorted(str(value) for value in graph.objects(subject, predicate))
    return values[0] if values else None


def extract_vocabulary(
    graph: rdflib.Graph,
    *,
    rdf_types: tuple[str, ...],
    primary_namespace: str | None = None,
) -> list[VocabularyTerm]:
    """Extract URI individuals whose ``rdf:type`` is one of ``rdf_types``."""
    selected: set[str] = set()
    type_nodes = tuple(URIRef(item) for item in rdf_types)
    for rdf_type in type_nodes:
        selected.update(
            str(subject)
            for subject in graph.subjects(RDF.type, rdf_type)
            if isinstance(subject, URIRef)
        )
    names = naming.disambiguate(
        {iri: naming.class_name(iri) for iri in selected},
        preferred_namespace=primary_namespace,
    )
    terms = []
    for iri in sorted(selected):
        subject = URIRef(iri)
        types = tuple(
            sorted(
                str(item)
                for item in graph.objects(subject, RDF.type)
                if isinstance(item, URIRef)
            )
        )
        terms.append(
            VocabularyTerm(
                name=names[iri],
                iri=iri,
                label=_text(graph, subject, RDFS.label),
                definition=_text(graph, subject, SKOS.definition),
                types=types,
            )
        )
    return terms


def emit_vocabulary_module(
    graph: rdflib.Graph,
    *,
    name: str,
    rdf_types: tuple[str, ...],
    primary_namespace: str | None = None,
    ontology_iri: str | None = None,
) -> str:
    """Render a deterministic module of :class:`TermValue` constants."""
    terms = extract_vocabulary(
        graph,
        rdf_types=rdf_types,
        primary_namespace=primary_namespace,
    )
    lines = [
        f'"""{name} vocabulary terms, generated by `objectrdf gen`."""',
        "",
        "# ruff: noqa",
        "from objectrdf.core import TermValue as _TermValue",
        "",
    ]
    for term in terms:
        args = [repr(term.iri)]
        if term.label is not None:
            args.append(f"label={term.label!r}")
        if term.definition is not None:
            args.append(f"definition={term.definition!r}")
        if term.types:
            args.append(f"types={term.types!r}")
        if ontology_iri is not None:
            args.append(f"ontology_iri={ontology_iri!r}")
        lines.append(f"{term.name} = _TermValue({', '.join(args)})")
    names = ",\n    ".join(repr(term.name) for term in terms)
    lines.append(f"\n__all__ = [\n    {names},\n]")
    return "\n".join(lines) + "\n"
